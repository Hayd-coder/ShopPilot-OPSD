"""Generate WebShop expert demonstrations without external trajectory data.

The generator uses WebShop's structured goal only as an offline oracle.  The
student prompt contains exactly the normal task, observation, history, and legal
actions.  Search queries are derived from task-visible text and never contain a
hidden ASIN or hidden product title.
"""

