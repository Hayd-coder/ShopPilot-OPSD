def sync_bundled_data(repo_root: Path, webshop_root: Path) -> None:
    source = repo_root / "datasets/webshop-small"
    destination = webshop_root / "data"
    destination.mkdir(parents=True, exist_ok=True)
    for name in (
        "items_shuffle_1000.json",
        "items_ins_v2_1000.json",
        "items_human_ins.json",
    ):
        source_file = source / name
        if not source_file.is_file():
            raise FileNotFoundError(source_file)
        destination_file = destination / name
        if not destination_file.is_file() or destination_file.stat().st_size != source_file.stat().st_size:
            shutil.copy2(source_file, destination_file)


def stable_rank(seed: int, goal_index: int, target_key: str) -> str:
    return hashlib.sha256(f"{seed}:{goal_index}:{target_key}".encode()).hexdigest()


def load_candidate_goal_indices(path: Path, goal_count: int) -> list[int]:
    indices: set[int] = set()
    with path.open(encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            record = json.loads(line)
            if "goal_index" not in record:
                raise ValueError(f"{path}:{line_number} has no goal_index")
            index = int(record["goal_index"])
            if not 0 <= index < goal_count:
                raise ValueError(
                    f"{path}:{line_number} goal_index {index} outside [0, {goal_count})"
                )
            indices.add(index)
    if not indices:
        raise ValueError(f"No goal_index values found in {path}")
    return sorted(indices)


def category_key(goal: dict[str, Any]) -> str:
    """Use the dataset's visible product taxonomy for split balancing."""
    return normalize_text(goal.get("product_category") or goal.get("category") or "unknown")


def stratum_key(goal: dict[str, Any]) -> str:
    """Group similar shopping tasks without using a target product identity."""
    return normalize_text(goal.get("query") or category_key(goal))


def category_balanced_order(
    indices: list[int],
    goals: list[dict[str, Any]],
    reference_counts: Counter[str],
    seed: int,
) -> list[int]:
    """Prioritize train ASINs from held-out task types without reusing held-out ASINs.

    This prevents an accidental category-OOD benchmark while preserving the
    stricter product-level (ASIN) separation.
    """
    buckets: dict[str, list[int]] = {}
    for index in indices:
        buckets.setdefault(stratum_key(goals[index]), []).append(index)
    for category, bucket in buckets.items():
        bucket.sort(
            key=lambda index: stable_rank(
                seed, index, goal_target_key(goals[index])
            )
        )

    reference_categories = [
        category for category, _ in reference_counts.most_common()
        if category in buckets
    ]
    if not reference_categories:
        return sorted(
            indices,
            key=lambda index: stable_rank(
                seed, index, goal_target_key(goals[index])
            ),
        )
    max_count = max(reference_counts[category] for category in reference_categories)
    weights = {
        category: max(
            1,
            math.ceil(5 * reference_counts[category] / max_count),
        )
        for category in reference_categories
    }
    ordered: list[int] = []
    while any(buckets[category] for category in reference_categories):
        for category in reference_categories:
            for _ in range(weights[category]):
                if buckets[category]:
                    ordered.append(buckets[category].pop())

    remaining = [index for bucket in buckets.values() for index in bucket]
    remaining.sort(
        key=lambda index: stable_rank(
            seed, index, goal_target_key(goals[index])
        )
    )
    ordered.extend(remaining)
    return ordered


def visible_query_candidates(task: str, goal: dict[str, Any]) -> list[str]:
    """Build queries only from strings already visible in the user task."""
    task_normalized = normalize_text(task)
    without_prefix = re.sub(r"^find me\s+", "", task_normalized)
    without_price = re.sub(r",?\s*and price lower than.*$", "", without_prefix)
    type_phrase = without_price.split(" with ", 1)[0].strip(" ,.")

    visible_attributes = [
        normalize_text(attribute)
        for attribute in goal.get("attributes", [])
        if normalize_text(attribute) in task_normalized
        and normalize_text(attribute) not in type_phrase
    ]
    structured_query = normalize_text(goal.get("query", ""))
    query_tokens = [token for token in re.findall(r"[a-z0-9]+", structured_query) if len(token) > 1]
    query_is_visible = bool(query_tokens) and all(token in task_normalized for token in query_tokens)

    candidates = [
        " ".join([type_phrase, *visible_attributes]).strip(),
        type_phrase,
    ]
    if query_is_visible:
        candidates.extend(
            [
                " ".join([structured_query, *visible_attributes]).strip(),
                structured_query,
            ]
        )
    unique: list[str] = []
    for candidate in candidates:
        candidate = normalize_text(re.sub(r"[^a-z0-9&' -]+", " ", candidate))
        if candidate and candidate not in unique and not ASIN_RE.search(candidate):
            unique.append(candidate)
    return unique


def visible_over_specific_query(task: str) -> str:
    """Use only user-visible text to form an intentionally strict first query."""
    normalized = normalize_text(task)
    normalized = re.sub(r"^find me\s+", "", normalized)
    normalized = re.sub(r",?\s*and price lower than.*$", "", normalized)
    normalized = re.sub(r"[^a-z0-9&' -]+", " ", normalized)
    return normalize_text(normalized)


def find_rewrite_query(
    env: Any,
    *,
    goal_index: int,
    task: str,
    fallback_queries: list[str],
    chosen_query: str,
    target_asin: str,
) -> str | None:
    """Find a visible query whose first page misses the target."""
    candidates = [visible_over_specific_query(task), *fallback_queries]
    seen: set[str] = set()
    for candidate in candidates:
        candidate = normalize_text(candidate)
        if not candidate or candidate == chosen_query or candidate in seen:
            continue
        seen.add(candidate)
        if locate_target(env, goal_index, candidate, target_asin, 1) is None:
            return candidate
    return None


def locate_target(
    env: Any,
    goal_index: int,
    query: str,
    target_asin: str,
    max_pages: int,
) -> dict[str, Any] | None:
    env.reset(session=goal_index)
    current_raw, _, done, _ = env.step(f"search[{query}]")
    if done:
        return None
    cumulative_rank = 0
    result_pages: list[list[str]] = []
    for page in range(max_pages):
        available = env.get_available_actions()
        result_asins = [
            str(item).upper()
            for item in available.get("clickables", [])
            if ASIN_RE.fullmatch(normalize_text(item))
        ]
        result_pages.append(result_asins)
        target = target_asin.upper()
        if target in result_asins:
            return {
                "page": page,
                "rank": cumulative_rank + result_asins.index(target) + 1,
                "result_pages": result_pages,
                "target_page_observation": current_raw,
            }
        cumulative_rank += len(result_asins)
        if page + 1 >= max_pages or "next >" not in {
            normalize_text(item) for item in available.get("clickables", [])
        }:
            break
        current_raw, _, _, _ = env.step("click[next >]")
    return None


def find_option_mismatch_distractor(
    env: Any,
    *,
    goal_index: int,
    query: str,
    target_asin: str,
    target_location: dict[str, Any],
    goal: dict[str, Any],
) -> dict[str, Any] | None:
    """Find an earlier result whose product page visibly lacks a required option.

    Only candidates ranked before the target are considered.  A candidate is
    rejected only when the required option value is absent from the actual
    clickable options on its product page; hidden metadata is not used to
    invent a rejection reason.
    """
    required = required_option_values(goal)
    if not required:
        return None

    preceding: list[tuple[int, int, str]] = []
    for page, result_asins in enumerate(target_location["result_pages"]):
        for index_on_page, asin in enumerate(result_asins):
            if page == target_location["page"] and asin == target_asin.upper():
                break
            preceding.append((page, index_on_page, asin))

    for page, index_on_page, candidate_asin in preceding:
        env.reset(session=goal_index)
        _, _, done, _ = env.step(f"search[{query}]")
        if done:
            continue
        legal_path = True
        for _ in range(page):
            available = env.get_available_actions()
            if "next >" not in {
                normalize_text(item) for item in available.get("clickables", [])
            }:
                legal_path = False
                break
            env.step("click[next >]")
        if not legal_path:
            continue
        available = env.get_available_actions()
        if not action_is_legal(f"click[{candidate_asin}]", available):
            continue
        candidate_raw, _, candidate_done, _ = env.step(f"click[{candidate_asin}]")
        if candidate_done:
            continue
        candidate_available = env.get_available_actions()
        visible_clickables = {
            normalize_text(item)
            for item in candidate_available.get("clickables", [])
        }
        missing = [value for value in required if value not in visible_clickables]
        if not missing:
            continue
        return {
            "asin": candidate_asin,
            "page": page,
            "index_on_page": index_on_page,
            "missing_required_options": missing,
            "observation": candidate_raw,
        }
    return None


def independent_terminal_check(goal: dict[str, Any], info: dict[str, Any], done: bool, target_price: float) -> tuple[bool, dict[str, Any]]:
    target_asin = normalize_text(goal.get("asin", ""))
    selected_asin = normalize_text(info.get("selected_asin", ""))
    required_options = goal.get("goal_options") or {}
    if isinstance(required_options, dict):
        required_options = required_options.values()
    required = [normalize_text(value) for value in required_options]
    selected_options = info.get("selected_options") or {}
    selected_values = [normalize_text(value) for value in selected_options.values()]
    missing = [value for value in required if value not in selected_values]
    price_upper = float(goal.get("price_upper", 0.0))
    price_ok = price_upper <= 0 or float(target_price) <= price_upper
    checks = {
        "done": bool(done),
        "asin_match": selected_asin == target_asin,
        "options_match": not missing,
        "price_ok": price_ok,
        "missing_options": missing,
        "selected_asin": info.get("selected_asin"),
        "selected_options": selected_options,
        "target_price": float(target_price),
        "price_upper": price_upper,
    }
    return all(checks[key] for key in ("done", "asin_match", "options_match", "price_ok")), checks


def main() -> None:
    args = parse_args()
    if not 0.0 <= args.comparison_fraction <= 1.0:
        raise ValueError("--comparison-fraction must be between 0 and 1")
    if not 0.0 <= args.rewrite_fraction <= 1.0:
        raise ValueError("--rewrite-fraction must be between 0 and 1")
    repo_root = Path(__file__).resolve().parents[2]
    webshop_root = repo_root / "agent_system/environments/env_package/webshop/webshop"
    sync_bundled_data(repo_root, webshop_root)
    index_marker = webshop_root / "search_engine/indexes_1k/segments_1"
    if not index_marker.is_file():
        raise FileNotFoundError(f"Missing verified 1k index: {index_marker}")

    sys.path.insert(0, str(repo_root))
    sys.path.insert(0, str(webshop_root))
    install_sparse_pyserini_shim()
    from web_agent_site.envs import WebAgentTextEnv  # noqa: PLC0415
    from agent_system.environments.prompts.webshop import (  # noqa: PLC0415
        WEBSHOP_TEMPLATE,
        WEBSHOP_TEMPLATE_NO_HIS,
    )

    env = WebAgentTextEnv(
        observation_mode="text",
        num_products=1000,
        human_goals=False,
        seed=args.goal_seed,
        goal_seed=args.goal_seed,
        file_path=str(webshop_root / "data/items_shuffle_1000.json"),
        attr_path=str(webshop_root / "data/items_ins_v2_1000.json"),
        session_prefix="self-oracle-",
    )
    goals = env.server.goals
    validation_size = 500 if len(goals) > 500 else max(1, len(goals) // 5)
    validation_asins = {
        normalize_text(goal.get("asin", "")) for goal in goals[:validation_size]
    }
    validation_target_keys = {
        goal_target_key(goal) for goal in goals[:validation_size]
    }
    heldout_stratum_counts = Counter(
        stratum_key(goal) for goal in goals[:validation_size]
    )
    heldout_category_counts = Counter(
        category_key(goal) for goal in goals[:validation_size]
    )
    if args.candidate_goal_index_jsonl:
        eligible = load_candidate_goal_indices(
            args.candidate_goal_index_jsonl, len(goals)
        )
        eligible.sort(
            key=lambda index: stable_rank(
                args.selection_seed, index, goal_target_key(goals[index])
            )
        )
        candidate_source = str(args.candidate_goal_index_jsonl.resolve())
    else:
        eligible = [
            index
            for index in range(validation_size, len(goals))
            if goal_target_key(goals[index]) not in validation_target_keys
            and (
                args.allow_heldout_asin_overlap
                or normalize_text(goals[index].get("asin", "")) not in validation_asins
            )
            and (
                not args.reference_strata_only
                or stratum_key(goals[index]) in heldout_stratum_counts
            )
        ]
        if args.reference_strata_only:
            eligible = category_balanced_order(
                eligible,
                goals,
                heldout_stratum_counts,
                args.selection_seed,
            )
        else:
            eligible.sort(
                key=lambda index: stable_rank(
                    args.selection_seed, index, goal_target_key(goals[index])
                )
            )
        candidate_source = "synthetic_goals_after_heldout_pool"

    args.output.parent.mkdir(parents=True, exist_ok=True)
    temporary_output = args.output.with_suffix(args.output.suffix + ".tmp")
    temporary_failures = args.failure_output.with_suffix(args.failure_output.suffix + ".tmp")
    success_count = 0
    attempt_count = 0
    total_steps = 0
    failure_counts: Counter[str] = Counter()
    rank_counts: Counter[str] = Counter()
    trajectory_mode_counts: Counter[str] = Counter()
    rejection_reason_counts: Counter[str] = Counter()
    comparison_requested_count = 0
    comparison_success_count = 0
    rewrite_requested_count = 0
    rewrite_success_count = 0
    asin_success_counts: Counter[str] = Counter()
    selected_category_counts: Counter[str] = Counter()
    selected_stratum_counts: Counter[str] = Counter()
    selected_target_keys: set[str] = set()

    with temporary_output.open("w", encoding="utf-8") as output_handle, temporary_failures.open("w", encoding="utf-8") as failure_handle:
        for goal_index in eligible:
            if success_count >= args.target_successes or attempt_count >= args.max_attempts:
                break
            goal = goals[goal_index]
            # WebShop may contain duplicate generated goals at different indices.
            # Keep only one trajectory for each exact target/task key so the
            # train/validation splitter cannot place the same task twice.
            if goal_target_key(goal) in selected_target_keys:
                continue
            target_asin = str(goal["asin"]).upper()
            if asin_success_counts[target_asin] >= args.max_goals_per_asin:
                continue
            attempt_count += 1
            task = str(goal["instruction_text"])
            queries = visible_query_candidates(task, goal)
            chosen: dict[str, Any] | None = None
            for query in queries:
                location = locate_target(
                    env, goal_index, query, target_asin, args.max_search_pages
                )
                if location is not None:
                    # Query priority is fixed before looking at target rank.  Use
                    # the first task-derived query that can retrieve the target,
                    # rather than cherry-picking the query that ranks it highest.
                    chosen = {"query": query, **location}
                    break
            if chosen is None:
                failure = {
                    "goal_index": goal_index,
                    "target_key": goal_target_key(goal),
                    "reason": "target_not_retrievable_with_visible_queries",
                    "query_candidates": queries,
                }
                failure_handle.write(json.dumps(failure, ensure_ascii=False) + "\n")
                failure_counts[failure["reason"]] += 1
                continue

            selection_evidence = visible_target_evidence(
                task,
                chosen["target_page_observation"],
                target_asin,
                float(goal.get("price_upper", 0.0)),
            )
            if selection_evidence is None:
                failure = {
                    "goal_index": goal_index,
                    "target_key": goal_target_key(goal),
                    "reason": "target_card_not_visible_for_grounding",
                    "search_query": chosen["query"],
                }
                failure_handle.write(json.dumps(failure, ensure_ascii=False) + "\n")
                failure_counts[failure["reason"]] += 1
                continue
            if (
                selection_evidence["target_overlap_count"]
                < args.min_visible_title_overlap
                or selection_evidence["overlap_gap_from_best"]
                > args.max_visible_rank_gap
                or not selection_evidence["visible_price_ok"]
            ):
                failure = {
                    "goal_index": goal_index,
                    "target_key": goal_target_key(goal),
                    "reason": "ambiguous_target_from_visible_result_card",
                    "search_query": chosen["query"],
                    "selection_evidence": selection_evidence,
                }
                failure_handle.write(json.dumps(failure, ensure_ascii=False) + "\n")
                failure_counts[failure["reason"]] += 1
                continue

            desired_comparison_count = math.ceil(
                (success_count + 1) * args.comparison_fraction
            )
            comparison_requested = (
                comparison_success_count < desired_comparison_count
            )
            distractor: dict[str, Any] | None = None
            if comparison_requested:
                comparison_requested_count += 1
                distractor = find_option_mismatch_distractor(
                    env,
                    goal_index=goal_index,
                    query=chosen["query"],
                    target_asin=target_asin,
                    target_location=chosen,
                    goal=goal,
                )
            desired_rewrite_count = math.ceil(
                (success_count + 1) * args.rewrite_fraction
            )
            rewrite_requested = rewrite_success_count < desired_rewrite_count
            rewrite_query: str | None = None
            if rewrite_requested:
                rewrite_requested_count += 1
                rewrite_query = find_rewrite_query(
                    env,
                    goal_index=goal_index,
                    task=task,
                    fallback_queries=queries,
                    chosen_query=chosen["query"],
                    target_asin=target_asin,
                )
            if rewrite_query and distractor:
                trajectory_mode = "rewrite_compare_reject_then_purchase"
            elif rewrite_query:
                trajectory_mode = "rewrite_then_purchase"
            elif distractor:
                trajectory_mode = "compare_reject_then_purchase"
            else:
                trajectory_mode = "direct_purchase"
            raw_observation, _ = env.reset(session=goal_index)
            extracted_task = extract_task(raw_observation)
            if normalize_text(extracted_task) != normalize_text(task):
                raise RuntimeError(f"Task mismatch at goal {goal_index}")
            observation = format_observation(raw_observation, extracted_task)
            history: list[dict[str, str]] = []
            trajectory_records: list[dict[str, Any]] = []
            failure_reason: str | None = None
            terminal_info: dict[str, Any] = {}
            terminal_reward = 0.0
            done = False

            def execute(
                action: str,
                *,
                think_override: str | None = None,
                decision_type: str = "normal",
            ) -> None:
                nonlocal observation, terminal_info, terminal_reward, done, failure_reason
                available = env.get_available_actions()
                if not action_is_legal(action, available):
                    failure_reason = f"illegal_oracle_action_turn_{len(history)}"
                    return
                prompt = build_prompt(
                    task=extracted_task,
                    observation=observation,
                    available=available,
                    history=history,
                    history_length=args.history_length,
                    no_history_template=WEBSHOP_TEMPLATE_NO_HIS,
                    history_template=WEBSHOP_TEMPLATE,
                )
                think = think_override or grounded_think(
                    action,
                    history,
                    goal,
                    task=extracted_task,
                    observation=observation,
                )
                response = f"<think>{think}</think>\n<action>{action}</action>"
                previous_observation = observation
                next_raw, reward, done_value, info = env.step(action)
                next_observation = format_observation(next_raw, extracted_task)
                trajectory_records.append(
                    {
                        "trajectory_id": goal_target_key(goal),
                        "goal_index": goal_index,
                        "turn": len(history),
                        "split": "train",
                        "source_dataset": "self_oracle_webshop_v3_visible_grounded",
                        "task": extracted_task,
                        "prompt": prompt,
                        "response": response,
                        "generated_think": think,
                        "think_source": "state_grounded_rules",
                        "expert_action": action,
                        "observation_before": previous_observation,
                        "admissible_actions_before": available,
                        "observation_after": next_observation,
                        "done": bool(done_value),
                        "step_reward": float(reward),
                        "selected_asin": info.get("selected_asin"),
                        "selected_options": info.get("selected_options", {}),
                        "target_asin": target_asin,
                        "target_options": goal.get("goal_options", {}),
                        "target_product_category": goal.get("product_category"),
                        "target_category_key": category_key(goal),
                        "target_query": goal.get("query"),
                        "target_stratum_key": stratum_key(goal),
                        "target_rank": chosen["rank"],
                        "target_page": chosen["page"],
                        "search_query": chosen["query"],
                        "initial_search_query": rewrite_query,
                        "trajectory_mode": trajectory_mode,
                        "decision_type": decision_type,
                        "selection_evidence": (
                            selection_evidence
                            if decision_type == "select_candidate"
                            else None
                        ),
                        "rejected_candidate_asin": (
                            distractor["asin"] if distractor else None
                        ),
                        "rejection_reason": (
                            {
                                "kind": "missing_required_options",
                                "values": distractor["missing_required_options"],
                            }
                            if distractor
                            else None
                        ),
                    }
                )
                history.append({"observation": previous_observation, "action": action})
                observation = next_observation
                terminal_info = dict(info or {})
                terminal_reward = float(reward)
                done = bool(done_value)

            if rewrite_query:
                execute(
                    f"search[{rewrite_query}]",
                    think_override=(
                        "I should begin with all visible task constraints, then "
                        "reformulate if the result page does not expose a clear match."
                    ),
                    decision_type="initial_over_specific_search",
                )
                if failure_reason is None:
                    execute(
                        "click[back to search]",
                        think_override=(
                            "The first result page does not expose a clear match for "
                            "the visible constraints, so I should return and retry "
                            "with the core product terms."
                        ),
                        decision_type="reformulate_search",
                    )
                if failure_reason is None:
                    execute(
                        f"search[{chosen['query']}]",
                        think_override=(
                            "The earlier query was too restrictive, so I should now "
                            "search with the core visible product terms."
                        ),
                        decision_type="refined_search",
                    )
            else:
                execute(f"search[{chosen['query']}]")
            current_result_page = 0
            if distractor is not None:
                for _ in range(distractor["page"]):
                    if failure_reason is None:
                        execute("click[next >]", decision_type="navigate_results")
                        current_result_page += 1
                missing_text = ", ".join(
                    f"'{value}'" for value in distractor["missing_required_options"]
                )
                if failure_reason is None:
                    execute(
                        f"click[{distractor['asin']}]",
                        think_override=(
                            "This is a plausible search result, but its required "
                            "options are not visible in the result list, so I should "
                            "open the product page and verify it before deciding."
                        ),
                        decision_type="inspect_candidate",
                    )
                if failure_reason is None:
                    execute(
                        "click[< Prev]",
                        think_override=(
                            f"The product page does not offer the required option(s) "
                            f"{missing_text}, so I should reject this candidate and "
                            "return to the search results."
                        ),
                        decision_type="reject_candidate",
                    )
            for _ in range(current_result_page, chosen["page"]):
                if failure_reason is None:
                    execute("click[next >]", decision_type="navigate_results")
            if failure_reason is None:
                execute(f"click[{target_asin}]", decision_type="select_candidate")
            goal_options = goal.get("goal_options") or {}
            option_items = sorted(goal_options.items()) if isinstance(goal_options, dict) else [(str(i), value) for i, value in enumerate(goal_options)]
            for _, option_value in option_items:
                if failure_reason is None:
                    execute(f"click[{normalize_text(option_value)}]")
            if failure_reason is None:
                execute("click[buy now]")

            target_price = float(env.server.product_prices[target_asin])
            independent_ok, independent_checks = independent_terminal_check(
                goal, terminal_info, done, target_price
            )
            if failure_reason is None and not independent_ok:
                failure_reason = "independent_terminal_check_failed"
            if failure_reason is not None:
                failure = {
                    "goal_index": goal_index,
                    "target_key": goal_target_key(goal),
                    "reason": failure_reason,
                    "search_query": chosen["query"],
                    "target_rank": chosen["rank"],
                    "target_page": chosen["page"],
                    "actions": [record["expert_action"] for record in trajectory_records],
                    "official_reward": terminal_reward,
                    "independent_checks": independent_checks,
                }
                failure_handle.write(json.dumps(failure, ensure_ascii=False) + "\n")
                failure_counts[failure_reason] += 1
                continue

            for record in trajectory_records:
                record["official_terminal_score"] = terminal_reward
                record["independent_success"] = True
                record["independent_checks"] = independent_checks
                output_handle.write(json.dumps(record, ensure_ascii=False) + "\n")
            success_count += 1
            total_steps += len(trajectory_records)
            asin_success_counts[target_asin] += 1
            selected_category_counts[category_key(goal)] += 1
            selected_stratum_counts[stratum_key(goal)] += 1
            selected_target_keys.add(goal_target_key(goal))
            trajectory_mode_counts[trajectory_mode] += 1
            if rewrite_query:
                rewrite_success_count += 1
            if distractor is not None:
                comparison_success_count += 1
                rejection_reason_counts["missing_required_options"] += 1
            rank_bucket = "1" if chosen["rank"] == 1 else "2-10" if chosen["rank"] <= 10 else "11+"
            rank_counts[rank_bucket] += 1
            if success_count % 10 == 0:
                print(
                    f"successful={success_count}/{args.target_successes} "
                    f"attempted={attempt_count} steps={total_steps}",
                    flush=True,
                )

    temporary_output.replace(args.output)
    temporary_failures.replace(args.failure_output)
    manifest = {
        "generator": "self_oracle_webshop_v3_visible_grounded",
        "uses_external_expert_trajectories": False,
        "uses_external_expert_actions": False,
        "uses_external_candidate_goal_indices": bool(
            args.candidate_goal_index_jsonl
        ),
        "goal_seed": args.goal_seed,
        "selection_seed": args.selection_seed,
        "num_goals": len(goals),
        "held_out_goal_count": validation_size,
        "held_out_asin_count": len(validation_asins),
        "held_out_target_key_count": len(validation_target_keys),
        "eligible_train_goal_count": len(eligible),
        "candidate_goal_source": candidate_source,
        "allow_heldout_asin_overlap": args.allow_heldout_asin_overlap,
        "reference_strata_only": args.reference_strata_only,
        "attempted_goals": attempt_count,
        "successful_trajectories": success_count,
        "sft_step_samples": total_steps,
        "failure_counts": dict(failure_counts),
        "target_rank_distribution": dict(rank_counts),
        "requested_comparison_fraction": args.comparison_fraction,
        "requested_rewrite_fraction": args.rewrite_fraction,
        "min_visible_title_overlap": args.min_visible_title_overlap,
        "max_visible_rank_gap": args.max_visible_rank_gap,
        "comparison_requested_goals": comparison_requested_count,
        "comparison_successful_trajectories": comparison_success_count,
        "rewrite_requested_goals": rewrite_requested_count,
        "rewrite_successful_trajectories": rewrite_success_count,
        "trajectory_mode_counts": dict(trajectory_mode_counts),
        "rejection_reason_counts": dict(rejection_reason_counts),
        "unique_training_asins": len(asin_success_counts),
        "held_out_asin_overlap": len(set(asin_success_counts) & {item.upper() for item in validation_asins}),
        "held_out_target_key_overlap": len(
            selected_target_keys & validation_target_keys
        ),
        "held_out_stratum_count": len(heldout_stratum_counts),
        "selected_stratum_count": len(selected_stratum_counts),
        "selected_heldout_stratum_overlap": len(
            set(selected_stratum_counts) & set(heldout_stratum_counts)
        ),
        "selected_stratum_distribution": dict(selected_stratum_counts),
        "held_out_category_count": len(heldout_category_counts),
        "selected_category_count": len(selected_category_counts),
        "selected_heldout_category_overlap": len(
            set(selected_category_counts) & set(heldout_category_counts)
        ),
        "selected_category_distribution": dict(selected_category_counts),
        "output": str(args.output.resolve()),
        "failure_output": str(args.failure_output.resolve()),
    }
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(manifest, ensure_ascii=False, indent=2), flush=True)
    if success_count < args.target_successes:
        raise RuntimeError(
            f"Generated only {success_count}/{args.target_successes} requested trajectories"
        )


if __name__ == "__main__":
    main()
