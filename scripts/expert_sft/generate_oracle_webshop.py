def normalize_text(value: Any) -> str:
    return " ".join(str(value).lower().split())


def parse_action(action: str) -> tuple[str | None, str | None]:
    match = re.fullmatch(
        r"\s*(search|click)\[(.*)]\s*", action, flags=re.IGNORECASE | re.DOTALL
    )
    if not match:
        return None, None
    return match.group(1).lower(), normalize_text(match.group(2))


def action_is_legal(action: str, available: dict[str, Any]) -> bool:
    action_name, value = parse_action(action)
    if action_name == "search":
        return bool(available.get("has_search_bar") and value)
    if action_name == "click":
        clickables = {normalize_text(item) for item in available.get("clickables", [])}
        return bool(value and value in clickables and value != "search")
    return False


def goal_target_key(goal: dict[str, Any]) -> str:
    values = goal.get("goal_options") or {}
    if isinstance(values, dict):
        values = values.values()
    counts = Counter(normalize_text(value) for value in values)
    options = "|".join(
        f"{value}#{count}" for value, count in sorted(counts.items())
    )
    return f"{str(goal.get('asin', '')).upper()}::{options}"


def required_option_values(goal: dict[str, Any]) -> list[str]:
    values = goal.get("goal_options") or {}
    if isinstance(values, dict):
        values = values.values()
    return [normalize_text(value) for value in values]


def extract_task(raw_observation: str) -> str:
    parts = raw_observation.split(" [SEP] ")
    if len(parts) < 3 or parts[1] != "Instruction:":
        raise ValueError(f"Cannot extract WebShop task from: {raw_observation[:300]!r}")
    return parts[2]


def format_observation(raw_observation: str, task: str) -> str:
    parts = raw_observation.split(" [SEP] ")
    try:
        task_index = parts.index(task)
    except ValueError:
        return raw_observation
    return " [SEP] ".join(f"'{part}'" for part in parts[task_index + 1 :])


VISIBLE_STOPWORDS = {
    "a", "an", "and", "are", "as", "at", "be", "below", "buy", "by",
    "dollar", "dollars", "find", "for", "from", "in", "is", "it", "lower",
    "me", "of", "on", "or", "price", "than", "that", "the", "this", "to",
    "under", "with", "your",
}


def informative_tokens(text: str) -> set[str]:
    return {
        token
        for token in re.findall(r"[a-z0-9]+", normalize_text(text))
        if len(token) > 1 and token not in VISIBLE_STOPWORDS and not token.isdigit()
    }


def parse_result_cards(observation: str) -> list[dict[str, Any]]:
    """Extract only facts visibly present in a WebShop result-page observation."""
    parts = [part.strip().strip("'") for part in observation.split(" [SEP] ")]
    cards: list[dict[str, Any]] = []
    for index, part in enumerate(parts):
        if not ASIN_RE.fullmatch(part):
            continue
        title = parts[index + 1] if index + 1 < len(parts) else ""
        price_text = parts[index + 2] if index + 2 < len(parts) else ""
        price_match = re.search(r"\$([0-9]+(?:\.[0-9]+)?)", price_text)
        cards.append(
            {
                "asin": part.upper(),
                "title": title,
                "price": float(price_match.group(1)) if price_match else None,
            }
        )
    return cards


def visible_target_evidence(
    task: str,
    observation: str,
    target_asin: str,
    price_upper: float,
) -> dict[str, Any] | None:
    """Score a target using only information available in the model prompt."""
    cards = parse_result_cards(observation)
    target = next(
        (card for card in cards if card["asin"] == target_asin.upper()), None
    )
    if target is None:
        return None
    task_tokens = informative_tokens(task)
    for card in cards:
        overlap = sorted(task_tokens & informative_tokens(card["title"]))
        card["overlap_terms"] = overlap
        card["overlap_count"] = len(overlap)
    best_overlap = max((card["overlap_count"] for card in cards), default=0)
    price = target["price"]
    return {
        "target_title": target["title"],
        "target_price": price,
        "price_upper": float(price_upper),
        "visible_price_ok": (
            price is None or price_upper <= 0 or float(price) <= float(price_upper)
        ),
        "overlap_terms": target["overlap_terms"],
        "target_overlap_count": target["overlap_count"],
        "best_visible_overlap_count": best_overlap,
        "overlap_gap_from_best": best_overlap - target["overlap_count"],
        "visible_candidate_count": len(cards),
    }


def format_available_actions(available: dict[str, Any]) -> str:
    unknown = set(available) - {"has_search_bar", "clickables"}
    if unknown:
        raise ValueError(f"Unknown available-action fields: {sorted(unknown)}")
    actions: list[str] = []
    if available.get("has_search_bar"):
        actions.append("search[<your query>]")
    actions.extend(f"click[{text}]" for text in available.get("clickables", []))
    return "\n".join(f"'{action}'," for action in actions)


def format_history(history: list[dict[str, str]], history_length: int) -> str:
    recent = history[-history_length:]
    start_index = len(history) - len(recent)
    lines = []
    for offset, record in enumerate(recent):
        step_number = start_index + offset + 1
        lines.append(
            f"[Observation {step_number}: '{record['observation']}', "
            f"Action {step_number}: '{record['action']}']"
        )
    return "\n".join(lines)


def build_prompt(
    *,
    task: str,
    observation: str,
    available: dict[str, Any],
    history: list[dict[str, str]],
    history_length: int,
    no_history_template: str,
    history_template: str,
) -> str:
    available_text = format_available_actions(available)
    if not history or history_length <= 0:
        return no_history_template.format(
            task_description=task,
            current_observation=observation,
            available_actions=available_text,
        )
    prompt = history_template.format(
        task_description=task,
        step_count=len(history),
        history_length=min(len(history), history_length),
        action_history=format_history(history, history_length),
        current_step=len(history) + 1,
        current_observation=observation,
        available_actions=available_text,
    )
    if len(prompt) > 13000:
        return no_history_template.format(
            task_description=task,
            current_observation=observation,
            available_actions=available_text,
        )
    return prompt


def grounded_think(
    action: str,
    history: list[dict[str, str]],
    goal: dict[str, Any],
    *,
    task: str,
    observation: str,
) -> str:
    action_name, value = parse_action(action)
    if action_name == "search":
        return "The current page has a search box, so I should search using the visible task constraints."
    if value == "next >":
        cards = parse_result_cards(observation)
        task_tokens = informative_tokens(task)
        best_terms: list[str] = []
        for card in cards:
            terms = sorted(task_tokens & informative_tokens(card["title"]))
            if len(terms) > len(best_terms):
                best_terms = terms
        if best_terms:
            visible_terms = ", ".join(f"'{term}'" for term in best_terms[:5])
            return (
                "The strongest visible title on this result page matches only "
                f"the terms {visible_terms}; more results are available, so I "
                "should inspect the next page before choosing."
            )
        return "No visible result title matches a specific task term, and more results are available, so I should inspect the next page."
    if value and ASIN_RE.fullmatch(value):
        evidence = visible_target_evidence(
            task,
            observation,
            value,
            float(goal.get("price_upper", 0.0)),
        )
        if evidence is not None:
            terms = evidence["overlap_terms"][:6]
            term_text = ", ".join(f"'{term}'" for term in terms)
            price = evidence["target_price"]
            facts: list[str] = []
            if terms:
                facts.append(f"its visible title matches task terms {term_text}")
            if price is not None and evidence["visible_price_ok"]:
                facts.append(
                    f"its visible price ${price:.2f} is within the user's limit"
                )
            if facts:
                return (
                    "This result is a strong visible candidate because "
                    + " and ".join(facts)
                    + ", so I should open it to verify the remaining details and options."
                )
        return (
            "This product is one of the visible candidates, so I should open "
            "its page and verify the details and selectable options before "
            "deciding whether to buy it."
        )

    required = required_option_values(goal)
    if value in required:
        return f"The user task requires option '{value}', and it is available on this page, so I should select it."
    if value == "buy now":
        selected = {
            parse_action(record["action"])[1]
            for record in history
            if parse_action(record["action"])[0] == "click"
        }
        if all(item in selected for item in required):
            return "The required selectable options are recorded in the visible action history, so I should submit the purchase."
        return "Buy Now is available, so I should submit the current selection for environment evaluation."
    return f"'{value}' is a legal action on the current page, so I should use it to continue the task."


